//! Regenerates the community built-in themes in `crates/theme/themes/`.
//!
//! ```sh
//! cargo run -p adoken-theme --example port_zeron_themes
//! ```
//!
//! The seed palettes below are zeron's curated adaptations of each upstream
//! VS Code theme, copied from zeron `crates/theme/src/builtins.rs` at
//! d1010657d69c9730f8020edc36cc2649b136b6fa (MIT); the upstream repository,
//! audited revision, license and copyright are kept per family. zeron's
//! "Shades of Purple" is not ported: its license asks that anything built
//! with it be MIT-licensed, which adoken is not. See THIRD_PARTY_NOTICES.md.
//!
//! Each seed palette goes through [`DraftVariant::from_seeds`] and
//! [`DraftVariant::enforce_contrast`];
//! every repair is written as a comment above its variant. `blue` and
//! `magenta` are the theme's terminal ANSI colors (bright on dark themes),
//! which feed `status.info.fg`/`text.link` and `pr.completed`.

use std::path::Path;

use adoken_theme::draft::{DraftFamily, DraftVariant, Seeds, SyntaxSeeds};
use adoken_theme::{Appearance, Color, THEME_FILE_SUFFIX, parse_theme};

struct Port {
    id: &'static str,
    name: &'static str,
    author: &'static str,
    url: &'static str,
    revision: &'static str,
    license: &'static str,
    copyright: &'static str,
    variants: &'static [Upstream],
}

struct Upstream {
    id: &'static str,
    name: &'static str,
    appearance: Appearance,
    background: &'static str,
    shell: &'static str,
    raised: &'static str,
    card: &'static str,
    text: &'static str,
    muted: &'static str,
    faint: &'static str,
    accent: &'static str,
    danger: &'static str,
    warning: &'static str,
    success: &'static str,
    blue: &'static str,
    magenta: &'static str,
    /// zeron order: comment, keyword, string, number, type, function,
    /// property, variable, punctuation, tag, attribute, invalid.
    syntax: [&'static str; 12],
}

impl Upstream {
    fn seeds(&self) -> Seeds {
        let c = |hex: &str| hex.parse::<Color>().expect("valid seed color");
        let [
            comment,
            keyword,
            string,
            number,
            type_name,
            function,
            property,
            variable,
            punctuation,
            tag,
            attribute,
            _invalid,
        ] = self.syntax.map(c);
        Seeds {
            appearance: self.appearance,
            background: c(self.background),
            shell: c(self.shell),
            raised: c(self.raised),
            card: c(self.card),
            text: c(self.text),
            muted: c(self.muted),
            faint: c(self.faint),
            accent: c(self.accent),
            danger: c(self.danger),
            warning: c(self.warning),
            success: c(self.success),
            info: c(self.blue),
            magenta: c(self.magenta),
            syntax: SyntaxSeeds {
                comment,
                keyword,
                string,
                number,
                type_name,
                function,
                property,
                variable,
                // zeron maps operators to the keyword color.
                operator: keyword,
                punctuation,
                tag,
                attribute,
            },
        }
    }
}

fn main() {
    let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("themes");
    for port in PORTS {
        let variants = port
            .variants
            .iter()
            .map(|upstream| {
                let mut variant =
                    DraftVariant::from_seeds(upstream.id, upstream.name, &upstream.seeds());
                let adjustments = variant.enforce_contrast();
                if adjustments.is_empty() {
                    variant.notes.push(
                        "No contrast adjustments: the upstream palette meets tokens.md §9.3."
                            .into(),
                    );
                } else {
                    variant.notes.push(
                        "Contrast adjustments (tokens.md §9.3, OKLab lightness only):".into(),
                    );
                    variant
                        .notes
                        .extend(adjustments.iter().map(|a| format!("  {a}")));
                }
                println!("{}: {} adjustment(s)", upstream.id, adjustments.len());
                variant
            })
            .collect();
        let family = DraftFamily {
            name: port.name.into(),
            author: Some(port.author.into()),
            license: Some(port.license.into()),
            notes: vec![
                format!("Built-in \"{}\", ported from {}", port.name, port.url),
                format!(
                    "at {} ({}; {}).",
                    port.revision, port.license, port.copyright
                ),
                "Seed palette: zeron crates/theme/src/builtins.rs at".into(),
                "d1010657d69c9730f8020edc36cc2649b136b6fa (MIT). See THIRD_PARTY_NOTICES.md."
                    .into(),
                "Generated by `cargo run -p adoken-theme --example port_zeron_themes`".into(),
                "(derivation: crates/theme/src/draft.rs). Edit the example, not this file.".into(),
            ],
            variants,
        };
        let source = family.to_toml();
        let loaded = parse_theme(port.id, &source, None).expect("generated file loads strict");
        assert!(loaded.issues.is_empty(), "{}: {:?}", port.id, loaded.issues);
        let path = dir.join(format!("{}{THEME_FILE_SUFFIX}", port.id));
        std::fs::write(&path, source).expect("write theme file");
    }
}

